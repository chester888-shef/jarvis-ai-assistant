api_key = os.getenv("GEMINI_API_KEY")

genai.configure(api_key=api_key)



model = genai.GenerativeModel(model_name="gemini-3.5-flash", system_instruction=SYSTEM_PROMPT)

while True:
    user_text = input("Ваше питання?: \n")
    if user_text.lower().strip() == "вихід":
        break

    response = model.generate_content(user_text, stream= True)


    print("Відповідь Джарвіса:")
    for chunk in response:
        print(chunk.text, end="")
    print("\n")